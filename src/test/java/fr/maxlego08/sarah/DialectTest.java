package fr.maxlego08.sarah;

import fr.maxlego08.sarah.conditions.ColumnDefinition;
import fr.maxlego08.sarah.database.DatabaseType;
import fr.maxlego08.sarah.dialect.Dialect;
import fr.maxlego08.sarah.dialect.Dialects;
import org.junit.jupiter.api.Test;

import static org.junit.jupiter.api.Assertions.assertEquals;

/**
 * SQL generated for each dialect, without a database.
 */
public class DialectTest {

    private static DatabaseConfiguration configuration(DatabaseType type) {
        return new DatabaseConfiguration("zm_", "user", "password", 5432, "localhost", "db", false, type);
    }

    @Test
    public void testPostgreSqlTranslatesQuotesOutsideLiterals() {
        Dialect dialect = Dialects.of(DatabaseType.POSTGRESQL);
        assertEquals("SELECT \"a\" FROM t WHERE \"b\" = 'it''s `raw`'", dialect.translate("SELECT `a` FROM t WHERE `b` = 'it''s `raw`'"));
    }

    @Test
    public void testPrepareReplacesPrefixAndQuotes() {
        assertEquals("SELECT \"id\" FROM zm_users", configuration(DatabaseType.POSTGRESQL).prepare("SELECT `id` FROM %prefix%users"));
        assertEquals("SELECT `id` FROM zm_users", configuration(DatabaseType.MYSQL).prepare("SELECT `id` FROM %prefix%users"));
    }

    @Test
    public void testPrefixWithRegexCharacters() {
        DatabaseConfiguration configuration = new DatabaseConfiguration("a$1_", "u", "p", 3306, "h", "d", false, DatabaseType.MYSQL);
        assertEquals("a$1_users", configuration.replacePrefix("%prefix%users"));
    }

    @Test
    public void testColumnTypes() {
        DatabaseConfiguration postgres = configuration(DatabaseType.POSTGRESQL);
        assertEquals("`data` TEXT NOT NULL", new ColumnDefinition("data", "LONGTEXT").build(postgres));
        assertEquals("`raw` BYTEA NULL", buildNullable("raw", "BLOB", postgres));
        assertEquals("`kind` VARCHAR(255) NOT NULL", new ColumnDefinition("kind", "ENUM").setEnumValues("A", "B").build(postgres));
        assertEquals("`kind` ENUM('A', 'B') NOT NULL", new ColumnDefinition("kind", "ENUM").setEnumValues("A", "B").build(configuration(DatabaseType.MYSQL)));
        assertEquals("`kind` TEXT NOT NULL", new ColumnDefinition("kind", "ENUM").setEnumValues("A", "B").build(DatabaseConfiguration.sqlite(false)));
    }

    private static String buildNullable(String name, String type, DatabaseConfiguration configuration) {
        ColumnDefinition column = new ColumnDefinition(name, type);
        column.setNullable(true);
        return column.build(configuration);
    }

    @Test
    public void testAutoIncrementColumns() {
        assertEquals("`id` BIGINT GENERATED BY DEFAULT AS IDENTITY NOT NULL", autoIncrement("BIGINT", DatabaseType.POSTGRESQL));
        assertEquals("`id` INTEGER GENERATED BY DEFAULT AS IDENTITY NOT NULL", autoIncrement("INTEGER", DatabaseType.POSTGRESQL));
        assertEquals("`id` BIGINT AUTO_INCREMENT NOT NULL", autoIncrement("BIGINT", DatabaseType.MYSQL));
        assertEquals("`id` INTEGER PRIMARY KEY AUTOINCREMENT", autoIncrement("BIGINT", DatabaseType.SQLITE));
    }

    private static String autoIncrement(String type, DatabaseType databaseType) {
        ColumnDefinition column = new ColumnDefinition("id", type).setAutoIncrement(true);
        column.setPrimaryKey(true);
        return column.build(databaseType == DatabaseType.SQLITE ? DatabaseConfiguration.sqlite(false) : configuration(databaseType));
    }

    @Test
    public void testLimitClauses() {
        assertEquals(" LIMIT 10 OFFSET 20", Dialects.of(DatabaseType.POSTGRESQL).limitClause(10, 20));
        assertEquals(" OFFSET 20", Dialects.of(DatabaseType.POSTGRESQL).limitClause(null, 20));
        assertEquals(" LIMIT -1 OFFSET 20", Dialects.of(DatabaseType.SQLITE).limitClause(null, 20));
        assertEquals(" LIMIT 18446744073709551615 OFFSET 20", Dialects.of(DatabaseType.MARIADB).limitClause(null, 20));
        assertEquals(" LIMIT 5", Dialects.of(DatabaseType.MYSQL).limitClause(5, null));
        assertEquals("", Dialects.of(DatabaseType.MYSQL).limitClause(null, null));
    }
}
