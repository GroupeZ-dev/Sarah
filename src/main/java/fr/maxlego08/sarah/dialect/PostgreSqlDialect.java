package fr.maxlego08.sarah.dialect;

import fr.maxlego08.sarah.DatabaseConfiguration;
import fr.maxlego08.sarah.conditions.ColumnDefinition;
import fr.maxlego08.sarah.database.DatabaseType;
import fr.maxlego08.sarah.database.Schema;

import java.sql.Connection;
import java.sql.PreparedStatement;
import java.sql.SQLException;
import java.sql.Statement;
import java.util.ArrayList;
import java.util.List;
import java.util.Locale;
import java.util.Map;

public class PostgreSqlDialect extends AbstractDialect {

    @Override
    public DatabaseType getType() {
        return DatabaseType.POSTGRESQL;
    }

    /**
     * Turns MySQL backtick quoting into standard double quotes, leaving string literals alone.
     * Quoted identifiers are case-sensitive in PostgreSQL, so a column must always be referenced
     * through Sarah (which always quotes) or in its exact case.
     */
    @Override
    public String translate(String sql) {
        StringBuilder builder = new StringBuilder(sql.length());
        boolean inLiteral = false;
        for (int index = 0; index < sql.length(); index++) {
            char character = sql.charAt(index);
            if (character == '\'') {
                inLiteral = !inLiteral;
                builder.append(character);
            } else if (character == '`' && !inLiteral) {
                builder.append('"');
            } else {
                builder.append(character);
            }
        }
        return builder.toString();
    }

    @Override
    public String mapType(String type) {
        if (type == null) {
            return null;
        }
        switch (type.toUpperCase(Locale.ROOT)) {
            case "LONGTEXT":
            case "MEDIUMTEXT":
            case "TINYTEXT":
                return "TEXT";
            case "BLOB":
            case "LONGBLOB":
            case "MEDIUMBLOB":
            case "TINYBLOB":
                return "BYTEA";
            case "DOUBLE":
                return "DOUBLE PRECISION";
            case "DATETIME":
                return "TIMESTAMP";
            case "TINYINT":
                return "SMALLINT";
            default:
                return type;
        }
    }

    @Override
    public String autoIncrementColumn(String columnType) {
        String type = columnType.toUpperCase(Locale.ROOT).startsWith("BIGINT") ? "BIGINT" : "INTEGER";
        return type + " GENERATED BY DEFAULT AS IDENTITY";
    }

    @Override
    public String enumFallbackType() {
        return "VARCHAR(255)";
    }

    /**
     * Asks for the auto-increment columns the schema declares. An insert schema usually only lists
     * the values it writes, so otherwise the driver is asked for every column of the new row
     * ({@code RETURNING *}) and the id is picked from it when the key is read.
     */
    @Override
    public PreparedStatement prepareInsert(Connection connection, String sql, Schema schema) throws SQLException {
        List<String> keys = new ArrayList<>();
        for (ColumnDefinition column : schema.getColumns()) {
            if (column.isAutoIncrement()) {
                keys.add(column.getName());
            }
        }
        if (keys.isEmpty()) {
            return connection.prepareStatement(sql, Statement.RETURN_GENERATED_KEYS);
        }
        return connection.prepareStatement(sql, keys.toArray(new String[0]));
    }

    @Override
    public String jdbcUrl(DatabaseConfiguration configuration) {
        return "jdbc:postgresql://" + configuration.getHost() + ":" + configuration.getPort() + "/" + configuration.getDatabase();
    }

    @Override
    public String driverClassName() {
        return "org.postgresql.Driver";
    }

    @Override
    public Map<String, String> dataSourceProperties() {
        Map<String, String> properties = super.dataSourceProperties();
        properties.put("reWriteBatchedInserts", "true");
        return properties;
    }
}
